# Variables are used to store data in a program. They can hold different types of values, 
# such as numbers, strings, lists, etc. 
# In this example, we are assigning the value 5 to the variable 'x' and then printing it to the console.

x = 5
print(x)
print("The value of x is:", x)

y = "Hello, World!" # Here we are assigning a string value to the variable 'y' and printing it to the console.
print(y)
print("The value of y is:", y)


