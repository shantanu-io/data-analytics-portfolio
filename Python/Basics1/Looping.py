# Looping Statements in Python
# Looping statements allow you to execute a block of code repeatedly as long as a specified condition is true. 
#  There are two main types of looping statements in Python: the while loop and the for loop.
# 1. While Loop: The while loop is used to execute a block of code repeatedly as long as a specified condition is true.
# Example:
i = 0
while i < 5:
    print("i is:", i)
    i += 1  

# 2. For Loop: The for loop is used to iterate over a sequence (such as a list, tuple, or string) and execute a block of code for each item in the sequence.
# Example:
for j in range(5):
    print("j is:", j)

        