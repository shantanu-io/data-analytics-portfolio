# Operators are special symbols that perform operations on variables and values. 
# In Python, we have several types of operators, including arithmetic, comparison, logical, assignment, and more.
# 1. Arithmetic Operators: These operators are used to perform mathematical operations like addition, subtraction, multiplication, division, etc.
# Example:  
a = 10
b = 5
print("Addition:", a + b)
print("Subtraction:", a - b)
print("Multiplication:", a * b)
print("Division:", a / b)
print("Modulus:", a % b)
print("Exponentiation:", a ** b)

# 2. Comparison Operators: These operators are used to compare two values and return a boolean result (True or False).
# Example:  
c = 10
d = 5
print("Equal:", c == d)
print("Not Equal:", c != d)
print("Greater Than:", c > d)
print("Less Than:", c < d)
print("Greater Than or Equal:", c >= d)
print("Less Than or Equal:", c <= d)

# 3. Logical Operators: These operators are used to combine conditional statements.
# Example:  
e = True
f = False
print("AND:", e and f)
print("OR:", e or f)
print("NOT:", not e)

# 4. Assignment Operators: These operators are used to assign values to variables.
# Example:
g = 10
print("Assignment:", g)
g += 5  # Equivalent to g = g + 5
print("Addition Assignment:", g)
g -= 3  # Equivalent to g = g - 3
print("Subtraction Assignment:", g)
g *= 2  # Equivalent to g = g * 2
print("Multiplication Assignment:", g)
g /= 4  # Equivalent to g = g / 4
print("Division Assignment:", g)


# 5. Membership Operators: These operators are used to test if a sequence is present in an object.
# Example:  
h = [1, 2, 3, 4, 5]
print("Is 3 in the list?", 3 in h)
print("Is 6 in the list?", 6 in h)
print("Is 3 not in the list?", 3 not in h)
print("Is 6 not in the list?", 6 not in h)

# 6. Identity Operators: These operators are used to compare the memory locations of two objects.
# Example:
i = 10
j = 10
print("Are i and j the same object?", i is j)
print("Are i and j not the same object?", i is not j)

# 7. Bitwise Operators: These operators are used to perform bit-level operations on binary numbers.
# Example:
x = 5  # Binary: 0101
y = 3  # Binary: 0011
print("AND:", x & y) # Bitwise AND &
print("OR:", x | y) # Bitwise OR |
print("XOR:", x ^ y) # Bitwise XOR ^
print("NOT x:", ~x) # Bitwise NOT ~
print("Left Shift:", x << 1) # Bitwise Left Shift <<
print("Right Shift:", x >> 1) # Bitwise Right Shift >>


